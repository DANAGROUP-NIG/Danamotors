import type { NextFunction, Request, RequestHandler, Response } from "express";
import prisma from "../../prisma/client";
import router from "./service.routes";
import { PERMISSIONS } from "../../shared/constants/roles";

type Layer = { route?: { path: string; methods: Record<string, boolean>; stack: { handle: RequestHandler }[] } };
const id = "11111111-1111-4111-8111-111111111111";
const requestId = "22222222-2222-4222-8222-222222222222";
const stack = (path: string, method: "get" | "post") => {
  const layer = (router.stack as Layer[]).find((entry) => entry.route?.path === path && entry.route.methods[method]);
  if (!layer?.route) throw new Error(`Missing route ${method} ${path}`);
  return layer.route.stack.map((entry) => entry.handle);
};
const request = (permissions: string[], body: unknown = {}, branchId: string | null = "home") =>
  ({ params: { id }, query: {}, body, user: { userId: "actor", role: "ServiceAdviser", permissions, branchId } }) as unknown as Request;
const response = () => {
  const res = { status: jest.fn(), json: jest.fn() };
  res.status.mockReturnValue(res);
  return res as unknown as Response & { status: jest.Mock; json: jest.Mock };
};
const findUnique = prisma.jobCard.findUnique as jest.Mock;

beforeEach(() => findUnique.mockReset());

it("needs job card read for the workspace and job card update for a stage action", () => {
  const [readPermission] = stack("/job-cards/:id/workspace", "get");
  const [updatePermission] = stack("/job-cards/:id/stage", "post");
  expect(() => readPermission(request([]), response(), jest.fn())).toThrow("required permissions");
  expect(() => updatePermission(request([PERMISSIONS.JOBCARD_READ]), response(), jest.fn())).toThrow("required permissions");
  const next = jest.fn();
  updatePermission(request([PERMISSIONS.JOBCARD_UPDATE]), response(), next);
  expect(next).toHaveBeenCalledWith();
});

it("rejects a missing request ID, an unknown action and a cancel without a reason, naming the field", async () => {
  const [, validate] = stack("/job-cards/:id/stage", "post");
  const check = async (body: unknown) => {
    const res = response();
    await validate(request([PERMISSIONS.JOBCARD_UPDATE], body), res, jest.fn());
    expect(res.status).toHaveBeenCalledWith(400);
    return res.json.mock.calls[0][0].errors as { field: string; message: string }[];
  };
  expect(await check({ action: "SEND_TO_SUPERVISOR" })).toEqual([expect.objectContaining({ field: "requestId", message: "Send the request ID the app generates for each step action" })]);
  expect(await check({ action: "FLY", requestId })).toEqual([
    expect.objectContaining({ field: "action", message: "Choose one of the actions shown for this step" }),
  ]);
  expect(await check({ action: "CANCEL", requestId })).toEqual([
    expect.objectContaining({ field: "note", message: "Give the reason for cancelling the job." }),
  ]);
  expect(await check({ action: "SEND_TO_SUPERVISOR", requestId: "not-a-uuid" })).toEqual([
    expect.objectContaining({ field: "requestId", message: "The request ID must be a UUID generated by the app" }),
  ]);
});

it("returns 404 for a missing job and 403 for another branch before acting", async () => {
  const handler = stack("/job-cards/:id/stage", "post").at(-1)!;
  const body = { action: "SEND_TO_SUPERVISOR", requestId };
  const next: jest.MockedFunction<NextFunction> = jest.fn();
  findUnique.mockResolvedValueOnce(null);
  await handler(request([PERMISSIONS.JOBCARD_UPDATE], body), response(), next);
  expect(next.mock.calls[0][0]).toMatchObject({ statusCode: 404, message: "Job card not found" });
  findUnique.mockResolvedValueOnce({ branchId: "other" });
  await handler(request([PERMISSIONS.JOBCARD_UPDATE], body), response(), next);
  expect(next.mock.calls[1][0]).toMatchObject({ statusCode: 403 });
});

it("returns the workspace for a job in the user's branch", async () => {
  const handler = stack("/job-cards/:id/workspace", "get").at(-1)!;
  findUnique.mockResolvedValueOnce({ branchId: "home" });
  const res = response();
  await handler(request([PERMISSIONS.JOBCARD_READ]), res, jest.fn());
  expect(res.json).toHaveBeenCalledWith({ status: "success", statusCode: 200, data: { stage: "CHECK_IN" } });
});
