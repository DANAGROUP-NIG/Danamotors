"""
Builds server/src/modules/labels/labels.logo.ts: the Kia logo as ZPL graphics for the part label.

  python hhdc/res/make_label_logo.py      (from the repo root; needs Pillow)

Source: client/public/logo.webp (the dashboard's logo, white on transparent, 100 x 23). Two graphics:
  KIA_LOGO   black logo, 112 dots wide (14 mm at 203 dpi), top right next to "Genuine Parts"
  KIA_BADGE  the black badge of the Kia labels: a rounded black box with the logo in white
Printed on the store's ZTC S4M and compared with Kia factory labels (user photos, 2026-11-23).
"""
import os
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = os.path.join(ROOT, "client", "public", "logo.webp")
OUT = os.path.join(ROOT, "server", "src", "modules", "labels", "labels.logo.ts")


def logo_mask(width):
    """The logo's shape at this width: 255 = logo, 0 = background (supersampled, then thresholded)."""
    alpha = Image.open(SRC).convert("RGBA").split()[3]
    height = round(alpha.size[1] * width / alpha.size[0])
    up = alpha.resize((width * 8, height * 8), Image.BICUBIC).resize((width, height), Image.BOX)
    return up.point(lambda v: 255 if v > 150 else 0)


def gfa(img):
    """^GFA for a 1-bit image (black = printed)."""
    w, h = img.size
    row = (w + 7) // 8
    data = []
    for y in range(h):
        bits = 0
        line = bytearray(row)
        for x in range(w):
            if img.getpixel((x, y)) == 0:
                line[x // 8] |= 0x80 >> (x % 8)
        data.append(line.hex().upper())
    total = row * h
    return "^GFA,%d,%d,%d,%s" % (total, total, row, "".join(data)), w, h


def logo():
    mask = logo_mask(112)
    img = Image.new("1", mask.size, 1)
    img.paste(0, mask=mask)
    return img


def badge():
    w, h = 104, 44
    img = Image.new("1", (w, h), 1)
    ImageDraw.Draw(img).rounded_rectangle((0, 0, w - 1, h - 1), radius=7, fill=0)
    mask = logo_mask(78)
    img.paste(1, ((w - mask.size[0]) // 2, (h - mask.size[1]) // 2), mask)
    return img


def main():
    lg, lw, lh = gfa(logo())
    bg, bw, bh = gfa(badge())
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by hhdc/res/make_label_logo.py from client/public/logo.webp: do not edit.\n")
        f.write("// The Kia logo as ZPL graphics (^GFA, 1 = black) for the part label.\n\n")
        f.write("export const KIA_LOGO = { width: %d, height: %d, zpl: \"%s\" };\n\n" % (lw, lh, lg))
        f.write("export const KIA_BADGE = { width: %d, height: %d, zpl: \"%s\" };\n" % (bw, bh, bg))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
